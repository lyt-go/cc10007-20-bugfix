def apply_domain_seed(tables: dict[str, list[dict[str, Any]]]) -> None:
    """把补偿字段和辅助表合入内存仓库。"""
    for row in tables.get("budget", []):
        row.update(BUDGET_ENRICH.get(str(row.get("方案编号")), {}))
    for row in tables.get("lifetime", []):
        row.update(LIFETIME_ENRICH.get(str(row.get("模型编号")), {}))
    lifetime_rows = tables.setdefault("lifetime", [])
    known = {str(row.get("模型编号")) for row in lifetime_rows}
    for row in EXTRA_LIFETIME:
        if row["模型编号"] not in known:
            lifetime_rows.append(dict(row))
    budget_rows = tables.setdefault("budget", [])
    known_plans = {str(row.get("方案编号")) for row in budget_rows}
    for row in EXTRA_BUDGET:
        if row["方案编号"] not in known_plans:
            budget_rows.append(dict(row))
    for name, rows in (
        ("ltv_value", LTV_VALUE_ROWS),
        ("channel_alloc", CHANNEL_ALLOC_ROWS),
        ("budget_dataset", DATASET_ROWS),
        ("ltv_pending", PENDING_ROWS),
        ("business_version", BUSINESS_VERSION_ROWS),
        ("budget_package", []),
        ("budget_receipt", []),
    ):
        table = tables.setdefault(name, [])
        if not table:
            table.extend(dict(row) for row in rows)
